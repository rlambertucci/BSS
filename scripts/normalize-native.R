arguments <- commandArgs(TRUE)
if (length(arguments) != 3L) stop("Expected source, isolated library and UTC build timestamp.")
source <- normalizePath(arguments[1L], winslash = "/", mustWork = TRUE)
library <- normalizePath(arguments[2L], winslash = "/", mustWork = TRUE)
installed <- file.path(library, "BSS")
if ("BSS" %in% loadedNamespaces()) stop("BSS must not be loaded before database generation.")
if (!isTRUE(l10n_info()[["UTF-8"]])) stop("Database generation requires a UTF-8 locale.")
.libPaths(c(library, .libPaths()))
original <- readRDS(file.path(installed, "Meta/package.rds"))
tools:::.install_package_code_files(source, installed)
tools:::makeLazyLoading("BSS", library, keep.source = FALSE, keep.parse.data = FALSE, set.install.dir = "BSS")
tools:::.install_package_description(source, installed, builtStamp = arguments[3L])
updated <- readRDS(file.path(installed, "Meta/package.rds"))
original$Built$Date <- updated$Built$Date
original$DESCRIPTION["Built"] <- updated$DESCRIPTION["Built"]
if (!identical(original, updated)) stop("Unexpected package metadata change during normalization.")
cat("PASS deterministic R metadata and lazy-load database from compiled sources.\n")
